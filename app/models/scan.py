"""Scan and Finding database models for SQLite persistence."""

from __future__ import annotations

from datetime import datetime
from uuid import uuid4

from sqlalchemy import JSON, DateTime, ForeignKey, Integer, String, Text
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.models.database import Base


class ScanModel(Base):
    """Represents a security scan execution."""

    __tablename__ = "scans"

    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=lambda: str(uuid4()))
    created_at: Mapped[datetime] = mapped_column(DateTime, default=datetime.utcnow, nullable=False)
    provider: Mapped[str] = mapped_column(String(32), nullable=False)
    format: Mapped[str] = mapped_column(String(32), nullable=False)
    scanner_version: Mapped[str] = mapped_column(String(32), nullable=False)
    policy_version: Mapped[str] = mapped_column(String(32), nullable=False)
    status: Mapped[str] = mapped_column(String(32), nullable=False, default="completed")

    risk_score: Mapped[int | None] = mapped_column(Integer, nullable=True)
    risk_band: Mapped[str | None] = mapped_column(String(32), nullable=True)

    total_resources: Mapped[int] = mapped_column(Integer, default=0)
    resources_evaluated: Mapped[int] = mapped_column(Integer, default=0)
    resources_unsupported: Mapped[int] = mapped_column(Integer, default=0)

    severity_counts: Mapped[dict] = mapped_column(JSON, default=dict)
    status_counts: Mapped[dict] = mapped_column(JSON, default=dict)

    parser_error_count: Mapped[int] = mapped_column(Integer, default=0)
    diagnostics_json: Mapped[list] = mapped_column(JSON, default=list)

    findings: Mapped[list[FindingModel]] = relationship(
        "FindingModel",
        back_populates="scan",
        cascade="all, delete-orphan",
        order_by="FindingModel.id",
    )


class FindingModel(Base):
    """Represents an individual security finding generated by a rule."""

    __tablename__ = "findings"

    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=lambda: str(uuid4()))
    scan_id: Mapped[str] = mapped_column(
        String(36), ForeignKey("scans.id", ondelete="CASCADE"), nullable=False, index=True
    )

    rule_id: Mapped[str] = mapped_column(String(64), nullable=False, index=True)
    provider: Mapped[str] = mapped_column(String(32), nullable=False)
    severity: Mapped[str] = mapped_column(String(32), nullable=False)
    status: Mapped[str] = mapped_column(
        String(32), nullable=False
    )  # PASS|FAIL|NOT_EVALUATED|UNSUPPORTED

    resource_id: Mapped[str] = mapped_column(String(256), nullable=False)
    resource_type: Mapped[str] = mapped_column(String(128), nullable=False)
    source_file: Mapped[str] = mapped_column(String(512), nullable=False)
    source_location: Mapped[str | None] = mapped_column(String(128), nullable=True)

    evidence: Mapped[str] = mapped_column(Text, nullable=False)
    remediation: Mapped[str] = mapped_column(Text, nullable=False)
    reference_urls: Mapped[list] = mapped_column(JSON, default=list)

    scan: Mapped[ScanModel] = relationship("ScanModel", back_populates="findings")
